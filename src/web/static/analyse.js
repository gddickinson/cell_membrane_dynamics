// Analyse page: choose the synthetic demo or your own mask TIFF (+ optional PIEZO1 TIFF), set the pixel size, frame
// interval and edge smoothing, and run the analysis in the browser (or, in the local app, in Python).
import { $, api, app, esc, isStatic, route } from './core.js';
import { rleDecode } from './rle.js';
import { readTiff } from './tiff_io.js';
import { runBrowser } from './run_engine.js';
import { renderResults } from './results.js';
import { state } from './state.js';

async function loadDemo() {
  const d = await api('/demo');
  return { label: d.label, synthetic: true, w: d.w, h: d.h, masks: d.rle.map(r => rleDecode(r, d.w * d.h)), fluor: null,
    umFromFile: d.um_per_px, dtFromFile: d.frame_s, scaleNote: 'suggested for the synthetic demo', maskFile: null, fluorFile: null };
}

async function loadUpload(maskFile, fluorFile) {
  const m = readTiff(await maskFile.arrayBuffer());
  const data = { label: maskFile.name, synthetic: false, w: m.w, h: m.h, masks: m.frames, fluor: null, umFromFile: m.umPerPx,
    dtFromFile: m.frameS, scaleNote: m.umPerPx ? `read from the file (${m.source})` : 'not in the file: enter it',
    maskFile, fluorFile: fluorFile || null, maskInfo: `${m.frames.length} frame(s), ${m.w} × ${m.h} px, ${m.bits}-bit, ${m.source}` };
  if (fluorFile) {
    const fl = readTiff(await fluorFile.arrayBuffer());
    if (fl.w !== m.w || fl.h !== m.h) throw new Error(`The PIEZO1 stack is ${fl.w} × ${fl.h} px but the masks are ${m.w} × ${m.h} px.`);
    if (fl.frames.length !== m.frames.length) throw new Error(`The PIEZO1 stack has ${fl.frames.length} frames, the masks ${m.frames.length}.`);
    data.fluor = fl.frames;
    data.fluorInfo = `${fl.frames.length} frame(s), ${fl.bits}-bit, ${fl.source}`;
  }
  return data;
}

