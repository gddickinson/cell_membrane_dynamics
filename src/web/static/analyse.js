async function run(fd, setStatus, prog) {
  const source = fd.get('source');
  let data = state.data;
  if (source === 'demo') { if (!data || !data.synthetic) data = await loadDemo(); }
  else {
    const mf = fd.get('masks'), ff = fd.get('fluorescence');
    if (!mf || !mf.name) throw new Error('Choose a mask TIFF first.');
    if (!data || data.maskFile !== mf || data.fluorFile !== (ff && ff.name ? ff : null)) data = await loadUpload(mf, ff && ff.name ? ff : null);
  }
  state.data = data;
  const u = +fd.get('um'), dt = +fd.get('dt'), sigma = +fd.get('sigma');
  if (!(u > 0) || !(dt > 0)) throw new Error('Pixel size and frame interval must be positive numbers.');
  if (!(sigma >= 0)) throw new Error('Edge smoothing must be 0 or more.');
  const n = data.masks.length, start = Math.max(1, Math.round(+fd.get('start') || 1)) - 1;
  const end = fd.get('end') ? Math.min(n, Math.round(+fd.get('end'))) - 1 : n - 1;
  if (start > end) throw new Error(`The first frame (${start + 1}) is after the last (${end + 1}); the stack has ${n} frame(s).`);
  const params = { um_per_px: u, pixel_size_nm: u * 1000, frame_s: dt, sigma, start, end, n_frames: n, shape: [data.h, data.w],
    scale_source: Math.abs(u - (data.umFromFile ?? NaN)) < 1e-12 ? data.scaleNote : 'entered by you' };
  if (fd.get('engine') === 'py') {
    setStatus('Running the Python pipeline...');
    const body = new FormData();
    for (const [k, v] of Object.entries({ source, um_per_px: u, frame_s: dt, sigma, start, end, use_demo_fluorescence: !!fd.get('flow') })) body.append(k, String(v));
    if (source !== 'demo') { body.append('masks', data.maskFile); if (fd.get('flow') && data.fluorFile) body.append('fluorescence', data.fluorFile); }
    const r = await api('/analyse', { body });
    return { ...r, params: { ...r.params, scale_source: params.scale_source } };
  }
  prog.classList.remove('hide'); prog.max = end - start + 1; prog.value = 0;
  const t0 = performance.now();
  const r = await runBrowser(data.masks, data.w, data.h, { pixelSizeNm: u * 1000, dt, sigma, start, end },
    i => { prog.value = i - start + 1; setStatus(`Frame ${i + 1} of ${end + 1}...`); });
  prog.classList.add('hide');
  return { ...r, engine: 'js', optical_flow: false, params, seconds: (performance.now() - t0) / 1000 };
}

route('analyse', async () => {
  const info = await api('/info');
  app().innerHTML = `<h1>Analyse a cell-mask sequence</h1>
    <p class="lead">Cell edge, membrane curvature, edge motion between frames and the curvature–motion correlation, frame by frame.</p>${form(info)}`;
  const f = $('#af'), status = $('#status'), prog = $('#prog'), meta = $('#meta');
  const setStatus = t => { status.textContent = t; };
  const sync = () => {
    const up = f.source.value === 'upload';
    $('#up').classList.toggle('hide', !up);
    const py = f.engine && f.engine.value === 'py';
    if ($('#flowopt')) $('#flowopt').classList.toggle('hide', !py);
  };
  const describe = async () => {
    try {
      let d = null;
      if (f.source.value === 'demo') d = state.data && state.data.synthetic ? state.data : await loadDemo();
      else if (f.masks.files[0]) d = await loadUpload(f.masks.files[0], f.fluorescence.files[0] || null);
      if (!d) { meta.textContent = ''; $('#scale').textContent = ''; return; }
      state.data = d;
      meta.textContent = d.synthetic ? `${d.masks.length} frames, ${d.w} × ${d.h} px` : `Masks: ${d.maskInfo}${d.fluorInfo ? ` · PIEZO1: ${d.fluorInfo}` : ''}`;
      if (d.umFromFile) f.um.value = d.umFromFile;
      if (d.dtFromFile) f.dt.value = d.dtFromFile;
      f.end.max = f.start.max = d.masks.length;
      $('#scale').textContent = `Pixel size: ${d.umFromFile ? `${d.umFromFile} µm/px, ${d.scaleNote}` : `not in the file; ${info.defaults.um_per_px} µm/px is the desktop app's default (100 nm), so check it`}.` +
        ` Frame interval: ${d.dtFromFile ? `${d.dtFromFile} s, ${d.synthetic ? d.scaleNote : 'read from the file'}` : 'not in the file, enter it'}.`;
    } catch (e) { meta.innerHTML = `<span class="err">${esc(e.message)}</span>`; }
  };
  f.addEventListener('change', e => { sync(); if (['source', 'masks', 'fluorescence'].includes(e.target.name)) describe(); });
  sync(); describe();
  f.addEventListener('submit', async e => {
    e.preventDefault();
    const btn = f.querySelector('button[type=submit]');
    btn.disabled = true;
    try {
      const res = await run(new FormData(f), setStatus, prog);
      state.result = res;
      setStatus(`Done: ${res.frames.length} frame(s) analysed${res.seconds ? ` in ${res.seconds.toFixed(1)} s` : ''}.`);
      renderResults($('#results'), res, state.data, info);
    } catch (err) {
      console.warn(err);
      prog.classList.add('hide');
      setStatus('');
      $('#results').innerHTML = `<p class="err">${esc(err.message)}</p>`;
    } finally { btn.disabled = false; }
  });
  if (state.result && state.data) renderResults($('#results'), state.result, state.data, info);
});
