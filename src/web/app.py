"""FastAPI web app for the PIEZO1 Membrane Dynamics Tracker: serves the front end in static/ and the JSON API.

Run with `python run_web.py` (http://127.0.0.1:8148, local only). `scripts/build_static.py` exports every path in
STATIC_ENDPOINTS to JSON for the GitHub Pages site, so keep that list in step with the GET routes below. On the
static site the analysis runs in the browser (contour_engine.js / dynamics_engine.js); POST /api/analyse runs the
repo's Python pipeline and adds Lucas-Kanade optical flow when a PIEZO1 stack is given.
"""
from pathlib import Path
from typing import Optional

from fastapi import FastAPI, File, Form, HTTPException, UploadFile
from fastapi.responses import FileResponse
from fastapi.staticfiles import StaticFiles

from ..analysis.edge_detection import EdgeDetector
from . import demo_data
from .analysis import AnalysisError, analyse, read_stack, summarise

STATIC = Path(__file__).resolve().parent / "static"
TITLE = "PIEZO1 Membrane Dynamics Tracker"
MAX_UPLOAD = 300 * 1024 * 1024

app = FastAPI(title=TITLE)
app.mount("/static", StaticFiles(directory=STATIC), name="static")


@app.get("/", include_in_schema=False)
def index():
    return FileResponse(STATIC / "index.html")


@app.get("/api/info")
def info():
    """Project summary and the analysis constants, read from the code where it exposes them."""
    ed = EdgeDetector()
    return {
        "title": TITLE, "version": "1",
        "defaults": {"um_per_px": 0.1, "frame_s": 1.0, "sigma": ed.smoothing_sigma, "min_size_px": ed.min_size,
                     "border_margin_px": 30, "stationary_nm_per_s": 10, "direction_threshold": 0.7,
                     "flow_weight": 0.7, "contour_weight": 0.3, "kymograph_full_scale_px_per_s": 50},
        "demo": {"frames": demo_data.N_FRAMES, "size": demo_data.SIZE, "um_per_px": demo_data.PIXEL_SIZE_UM,
                 "frame_s": demo_data.FRAME_INTERVAL_S},
    }


@app.get("/api/demo")
def demo():
    """The synthetic demo mask stack (run-length encoded, see demo_data.rle_encode)."""
    masks = demo_data.demo_masks()
    return {"w": demo_data.SIZE, "h": demo_data.SIZE, "n": len(masks), "rle": [demo_data.rle_encode(m) for m in masks],
            "um_per_px": demo_data.PIXEL_SIZE_UM, "frame_s": demo_data.FRAME_INTERVAL_S,
            "label": "Synthetic demo (generated by src/web/demo_data.py; not real microscopy data)"}


@app.get("/api/demo/python")
def demo_python():
    """Per-frame summary of the demo masks through the repo's Python pipeline (no optical flow), for comparison
    with the browser engine."""
    return summarise(analyse(list(demo_data.demo_masks()), None, demo_data.PIXEL_SIZE_UM, demo_data.FRAME_INTERVAL_S))


async def _read(f: Optional[UploadFile], what: str):
    if f is None or not f.filename:
        return None, None, None
    data = await f.read(MAX_UPLOAD + 1)
    if len(data) > MAX_UPLOAD:
        raise HTTPException(413, f"The {what} is larger than {MAX_UPLOAD // 2**20} MB.")
    return read_stack(data, what)


@app.post("/api/analyse")
async def analyse_upload(source: str = Form("demo"), um_per_px: float = Form(0.1), frame_s: float = Form(1.0),
                         sigma: float = Form(1.0), start: int = Form(0), end: int = Form(-1),
                         use_demo_fluorescence: bool = Form(False),
                         masks: Optional[UploadFile] = File(None), fluorescence: Optional[UploadFile] = File(None)):
    """Full Python analysis of the demo or an uploaded mask stack (+ optional PIEZO1 stack for optical flow)."""
    try:
        if source == "demo":
            m = list(demo_data.demo_masks())
            fl = list(demo_data.demo_fluorescence()) if use_demo_fluorescence else None
        else:
            m, _, _ = await _read(masks, "mask stack")
            if m is None:
                raise AnalysisError("Choose a mask TIFF.")
            fl, _, _ = await _read(fluorescence, "PIEZO1 stack")
        return analyse(m, fl, um_per_px, frame_s, sigma, start, None if end < 0 else end)
    except AnalysisError as e:
        raise HTTPException(400, str(e)) from e


# GET paths (without the /api prefix) written to the static site as api/<path>.json.
STATIC_ENDPOINTS = ["/info", "/demo", "/demo/python"]
